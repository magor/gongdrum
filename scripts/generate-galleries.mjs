import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const publicObrazky = path.join(root, 'site/public/obrazky');
const publicAudio = path.join(root, 'site/public/audio');
const manifestFile = path.join(root, 'site/src/generated/image-manifest.json');
const outFile = path.join(root, 'site/src/generated/galleries.ts');
const backgroundCssFile = path.join(root, 'site/src/generated/background.css');

const IMAGE_RE = /\.(jpe?g|png|webp|gif)$/i;

function syncLegacyAssets() {
  const rootObrazky = path.join(root, 'obrazky');
  const rootAudio = path.join(root, 'audio');

  if (fs.existsSync(rootObrazky)) {
    for (const entry of fs.readdirSync(rootObrazky, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;

      const srcDir = path.join(rootObrazky, entry.name);
      const destDir = path.join(publicObrazky, entry.name);
      fs.mkdirSync(destDir, { recursive: true });

      for (const file of fs.readdirSync(srcDir)) {
        if (file.startsWith('.')) continue;
        fs.copyFileSync(path.join(srcDir, file), path.join(destDir, file));
      }
    }
  }

  if (fs.existsSync(rootAudio)) {
    fs.mkdirSync(publicAudio, { recursive: true });
    for (const file of fs.readdirSync(rootAudio)) {
      if (!file.endsWith('.mp3')) continue;
      fs.copyFileSync(path.join(rootAudio, file), path.join(publicAudio, file));
    }
  }
}

function readManifest() {
  if (!fs.existsSync(manifestFile)) return {};
  return JSON.parse(fs.readFileSync(manifestFile, 'utf8')).images ?? {};
}

function listSourceImages(slug) {
  const dir = path.join(publicObrazky, slug);
  if (!fs.existsSync(dir)) return [];

  return fs
    .readdirSync(dir)
    .filter((file) => IMAGE_RE.test(file))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }))
    .map((file) => `obrazky/${slug}/${file}`);
}

function toOptimizedImage(relativePath, manifest) {
  const manifestKey = relativePath.startsWith('obrazky/')
    ? relativePath.slice('obrazky/'.length)
    : relativePath;
  const entry = manifest[manifestKey];
  if (!entry) {
    const fallback = `./${relativePath}`;
    return {
      source: fallback,
      width: 0,
      height: 0,
      variants: {
        card: { jpeg: fallback, webp: fallback },
        display: { jpeg: fallback, webp: fallback },
      },
    };
  }

  return {
    source: entry.source,
    width: entry.width,
    height: entry.height,
    variants: entry.variants,
  };
}

function toRootPath(relativePath) {
  if (relativePath.startsWith('./')) return relativePath.slice(1);
  if (relativePath.startsWith('/')) return relativePath;
  return `/${relativePath}`;
}

function audioPath(slug) {
  const file = path.join(publicAudio, `${slug}.mp3`);
  return fs.existsSync(file) ? `./audio/${slug}.mp3` : undefined;
}

syncLegacyAssets();

const manifest = readManifest();
const slugs = fs
  .readdirSync(publicObrazky, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const galleries = Object.fromEntries(
  slugs.map((slug) => [
    slug,
    listSourceImages(slug).map((relativePath) => toOptimizedImage(relativePath, manifest)),
  ]),
);

const sharedImagePaths = [
  'obrazky/logo_upraveno.png',
  'obrazky/vesmirna_mlhovina.png',
  'obrazky/workshop_vyroby_gongdrumu.jpg',
];

const sharedImages = Object.fromEntries(
  sharedImagePaths.map((relativePath) => {
    const key = path.basename(relativePath, path.extname(relativePath));
    return [key, toOptimizedImage(relativePath, manifest)];
  }),
);

const drumAudio = Object.fromEntries(
  slugs.flatMap((slug) => {
    const audio = audioPath(slug);
    return audio ? [[slug, audio]] : [];
  }),
);

const imageCount = Object.values(galleries).flat().length;

const content = `// Auto-generated by scripts/generate-galleries.mjs — do not edit manually.
import type { OptimizedImage } from '../images';

export const galleries: Record<string, OptimizedImage[]> = ${JSON.stringify(galleries, null, 2)};

export const sharedImages: Record<string, OptimizedImage> = ${JSON.stringify(sharedImages, null, 2)};

export const drumAudio: Record<string, string> = ${JSON.stringify(drumAudio, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content);

const background = sharedImages.vesmirna_mlhovina.variants.display.jpeg;
const backgroundPath = toRootPath(background);
fs.writeFileSync(
  backgroundCssFile,
  `/* Auto-generated by scripts/generate-galleries.mjs — do not edit manually. */
body::before {
  background-image: url('${backgroundPath}');
}
`,
);

console.log(
  `Generated galleries for ${slugs.length} folders (${imageCount} images, ${Object.keys(drumAudio).length} audio tracks).`,
);
