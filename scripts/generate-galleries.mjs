import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const publicObrazky = path.join(root, 'site/public/obrazky');
const publicAudio = path.join(root, 'site/public/audio');
const outFile = path.join(root, 'site/src/generated/galleries.ts');

const IMAGE_RE = /\.(jpe?g|png|webp|gif)$/i;

function syncLegacyAssets() {
  const rootObrazky = path.join(root, 'obrazky');
  const rootAudio = path.join(root, 'audio');

  if (fs.existsSync(rootObrazky)) {
    for (const entry of fs.readdirSync(rootObrazky, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;

      const srcDir = path.join(rootObrazky, entry.name);
      const destDir = path.join(publicObrazky, entry.name);
      fs.mkdirSync(destDir, { recursive: true });

      for (const file of fs.readdirSync(srcDir)) {
        if (file.startsWith('.')) continue;
        fs.copyFileSync(path.join(srcDir, file), path.join(destDir, file));
      }
    }
  }

  if (fs.existsSync(rootAudio)) {
    fs.mkdirSync(publicAudio, { recursive: true });
    for (const file of fs.readdirSync(rootAudio)) {
      if (!file.endsWith('.mp3')) continue;
      fs.copyFileSync(path.join(rootAudio, file), path.join(publicAudio, file));
    }
  }
}

function listImages(slug) {
  const dir = path.join(publicObrazky, slug);
  if (!fs.existsSync(dir)) return [];

  return fs
    .readdirSync(dir)
    .filter((file) => IMAGE_RE.test(file))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }))
    .map((file) => `./obrazky/${slug}/${file}`);
}

function audioPath(slug) {
  const file = path.join(publicAudio, `${slug}.mp3`);
  return fs.existsSync(file) ? `./audio/${slug}.mp3` : undefined;
}

syncLegacyAssets();

const slugs = fs
  .readdirSync(publicObrazky, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const galleries = Object.fromEntries(slugs.map((slug) => [slug, listImages(slug)]));
const drumAudio = Object.fromEntries(
  slugs.flatMap((slug) => {
    const audio = audioPath(slug);
    return audio ? [[slug, audio]] : [];
  }),
);

const content = `// Auto-generated by scripts/generate-galleries.mjs — do not edit manually.
export const galleries: Record<string, string[]> = ${JSON.stringify(galleries, null, 2)};

export const drumAudio: Record<string, string> = ${JSON.stringify(drumAudio, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content);

console.log(
  `Generated galleries for ${slugs.length} folders (${Object.values(galleries).flat().length} images, ${Object.keys(drumAudio).length} audio tracks).`,
);
